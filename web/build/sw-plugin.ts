import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';

/**
 * Source of the generated service worker.
 *
 * Kept as an inlined string rather than a separate file that gets read at build
 * time: Vite bundles `vite.config.ts` (and everything it imports) into a temp
 * module, so `import.meta.url` / `__dirname` here do not reliably point at this
 * directory. Inlining keeps the build hermetic.
 *
 * Deliberately written without template literals so `${...}` cannot collide with
 * the surrounding TS template string.
 */
function swSource(manifest: readonly string[], version: string): string {
  return [
    "// Generated by build/sw-plugin.ts — do not edit by hand.",
    "'use strict';",
    '',
    'const VERSION = ' + JSON.stringify(version) + ';',
    "const SHELL_CACHE = 'reactionlab-shell-' + VERSION;",
    "const FONT_CACHE = 'reactionlab-fonts';",
    'const PRECACHE = ' + JSON.stringify(manifest, null, 2) + ';',
    '',
    'const FONT_ORIGINS = [',
    "  'https://fonts.googleapis.com',",
    "  'https://fonts.gstatic.com',",
    '];',
    '',
    'self.addEventListener("install", (event) => {',
    '  event.waitUntil(',
    '    caches',
    '      .open(SHELL_CACHE)',
    '      // addAll() is all-or-nothing; add individually so one miss cannot',
    '      // abort the whole install.',
    '      .then((cache) =>',
    '        Promise.all(',
    '          PRECACHE.map((url) =>',
    '            cache.add(new Request(url, { cache: "reload" })).catch(() => undefined),',
    '          ),',
    '        ),',
    '      )',
    '      .then(() => self.skipWaiting()),',
    '  );',
    '});',
    '',
    'self.addEventListener("activate", (event) => {',
    '  event.waitUntil(',
    '    caches',
    '      .keys()',
    '      .then((keys) =>',
    '        Promise.all(',
    '          keys',
    '            .filter((key) => key !== SHELL_CACHE && key !== FONT_CACHE)',
    '            .filter((key) => key.startsWith("reactionlab-"))',
    '            .map((key) => caches.delete(key)),',
    '        ),',
    '      )',
    '      .then(() => self.clients.claim()),',
    '  );',
    '});',
    '',
    'self.addEventListener("message", (event) => {',
    '  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();',
    '});',
    '',
    '// Stale-while-revalidate: answer from cache instantly, refresh in the',
    '// background. Used for the app shell document and for the font CDN.',
    'function staleWhileRevalidate(request, cacheName) {',
    '  return caches.open(cacheName).then((cache) =>',
    '    cache.match(request).then((cached) => {',
    '      const network = fetch(request)',
    '        .then((response) => {',
    '          if (response && (response.ok || response.type === "opaque")) {',
    '            cache.put(request, response.clone());',
    '          }',
    '          return response;',
    '        })',
    '        .catch(() => undefined);',
    '      return cached || network.then((r) => r || Response.error());',
    '    }),',
    '  );',
    '}',
    '',
    '// Cache-first: every emitted asset is content-hashed, so a hit is always',
    '// the right bytes and never needs revalidating.',
    'function cacheFirst(request, cacheName) {',
    '  return caches.open(cacheName).then((cache) =>',
    '    cache.match(request).then((cached) => {',
    '      if (cached) return cached;',
    '      return fetch(request).then((response) => {',
    '        if (response && response.ok) cache.put(request, response.clone());',
    '        return response;',
    '      });',
    '    }),',
    '  );',
    '}',
    '',
    'self.addEventListener("fetch", (event) => {',
    '  const request = event.request;',
    '  if (request.method !== "GET") return;',
    '',
    '  const url = new URL(request.url);',
    '',
    '  if (request.mode === "navigate") {',
    '    event.respondWith(',
    '      staleWhileRevalidate(new Request("/index.html"), SHELL_CACHE).catch(() =>',
    '        caches.match("/offline.html").then((r) => r || Response.error()),',
    '      ),',
    '    );',
    '    return;',
    '  }',
    '',
    '  if (FONT_ORIGINS.indexOf(url.origin) !== -1) {',
    '    event.respondWith(staleWhileRevalidate(request, FONT_CACHE));',
    '    return;',
    '  }',
    '',
    '  if (url.origin !== self.location.origin) return;',
    '',
    '  event.respondWith(',
    '    cacheFirst(request, SHELL_CACHE).catch(() =>',
    '      caches.match(request).then((r) => r || Response.error()),',
    '    ),',
    '  );',
    '});',
    '',
  ].join('\n');
}

/**
 * Emits `sw.js` at build time with a precache manifest of every asset Vite
 * produced, plus a cache version derived from those asset names.
 */
export function serviceWorkerPlugin(): Plugin {
  return {
    name: 'reactionlab:service-worker',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      // Files served straight out of `public/` never appear in the rollup
      // bundle, so they are listed explicitly.
      const assets = new Set<string>([
        '/',
        '/index.html',
        '/manifest.json',
        '/offline.html',
        '/favicon.svg',
        '/icons/icon-192.png',
        '/icons/icon-512.png',
        '/icons/maskable-512.png',
        '/icons/apple-touch-icon.png',
      ]);

      for (const fileName of Object.keys(bundle)) {
        if (fileName === 'sw.js') continue; // never precache the worker itself
        assets.add('/' + fileName);
      }

      const manifest = [...assets].sort();
      const version = createHash('sha256').update(manifest.join('\n')).digest('hex').slice(0, 12);

      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(manifest, version) });
    },
  };
}
